constexpr std::uint16_t objective_row(
	std::uint16_t mission_number,
	bool mission_25_alternate)
{
	if (mission_number == 25 && mission_25_alternate)
	{
		return 35;
	}
	return mission_number >= 1 && mission_number <= 36
		? static_cast<std::uint16_t>(mission_number - 1)
		: UINT16_MAX;
}

constexpr std::uint16_t objective_language_id(
	std::uint16_t mission_number,
	bool mission_25_alternate,
	std::uint16_t objective)
{
	const std::uint16_t row =
		objective_row(mission_number, mission_25_alternate);
	return row < 36 && objective < 10
		? kObjectiveLanguageIds[row][objective]
		: UINT16_MAX;
}

