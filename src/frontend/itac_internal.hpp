inline std::uint8_t squad_count(const ItacShell& shell)
{
	if (shell.squad_faction != 0)
	{
		return static_cast<std::uint8_t>(
			sizeof(kCoalitionSquads) / sizeof(kCoalitionSquads[0]));
	}
	std::uint8_t count = 0;
	for (const SquadRecord& record : kAllianceSquads)
	{
		const bool hidden =
			(record.name == 456 && shell.scenario_id >= 13)
			|| (record.name == 457 && shell.scenario_id < 13)
			|| (record.name == 459 && shell.scenario_id > 9);
		if (!hidden) ++count;
	}
	return count;
}

